import { chromium } from "playwright-core";
const UI = "http://127.0.0.1:3110";
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.goto(UI + "/s/9a9a9a9a9a9a");
await p.waitForTimeout(8000); await p.screenshot({ path: "qa/dbg.png" }); await p.waitForSelector("[data-testid=archived-banner]", { timeout: 20000 });
await p.waitForTimeout(1500);
console.log("rows:", await p.locator("[data-testid=timeline-scroll] > div").count(), "(expect 600)");
await p.screenshot({ path: "qa/10-paged-archived.png" });
await p.goto(UI + "/s/a5af842a89e1");
await p.waitForSelector("text=Live", { timeout: 60000 });
await p.waitForTimeout(5000);
console.log("live rows:", await p.locator("[data-testid=timeline-scroll] > div").count(), "errors:", errs.length);
await b.close();
